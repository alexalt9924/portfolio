def bullet():
    frames = []
    cols = ["#FFCC00", "#FFFF66", "#FFFFFF", "#FFFF66"]
    for i, core in enumerate(cols):
        img = Image.new("RGBA", (15, 15), (0, 0, 0, 0))
        d = draw_for(img)
        c = 7
        arm = 7 if i == 2 else 5
        d.line([(c, c - arm), (c, c + arm)], fill="#FF9900")
        d.line([(c - arm, c), (c + arm, c)], fill="#FF9900")
        d.point([(c - 2, c - 2), (c + 2, c - 2), (c - 2, c + 2), (c + 2, c + 2)], fill="#CC6600")
        d.rectangle((c - 1, c - 1, c + 1, c + 1), fill=core)
        frames.append(img)
    save_anim(frames, "bullet.gif", 160)


def new_tag():
    fnt = font(SANS_BOLD, 10)
    frames = []
    for bg, fg in [("#FF0000", "#FFFFFF"), ("#FF0000", "#FFFF00")]:
        img = Image.new("RGB", (32, 14), bg)
        d = draw_for(img)
        d.rectangle((0, 0, 31, 13), outline="#990000")
        centered_text(d, (0, 0, 31, 13), "NEW!", fnt, fg)
        frames.append(img)
