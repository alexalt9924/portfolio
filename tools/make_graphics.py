def counter():
    """Odometer counter pieces: one tile per digit plus left/right end caps.

    The page lines them up as  counter_left + digits... + counter_right.
    """
    dw, dh = 15, 21
    h = dh + 4
    fnt = font(MONO_BOLD, 17)
    for ch in "0123456789":
        img = Image.new("RGB", (dw + 1, h), "#666666")
        d = draw_for(img)
        d.line([(0, 0), (dw, 0)], fill="#000000")
        d.line([(0, h - 1), (dw, h - 1)], fill="#000000")
        d.rectangle((0, 2, dw - 1, 2 + dh - 1), fill="#000000")
        d.rectangle((0, 2 + dh // 2, dw - 1, 2 + dh - 1), fill="#111111")
        centered_text(d, (0, 2, dw - 1, 2 + dh - 1), ch, fnt, "#FFFFFF")
        d.line([(0, 2 + dh // 2), (dw - 1, 2 + dh // 2)], fill="#333333")
        save(img, f"counter_{ch}.gif")
    left = Image.new("RGB", (2, h), "#666666")
    d = draw_for(left)
    d.line([(0, 0), (0, h - 1)], fill="#000000")
    d.line([(0, 0), (1, 0)], fill="#000000")
    d.line([(0, h - 1), (1, h - 1)], fill="#000000")
    save(left, "counter_left.gif")
    save(Image.new("RGB", (1, h), "#000000"), "counter_right.gif")


