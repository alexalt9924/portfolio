"""Generate the site's GIF graphics in a late-90s, FrontPage-theme style.

Text is rendered without anti-aliasing and colours are kept to the
web-safe palette so the images look like they came out of a 1998
graphics package. Re-run after changing labels or the banner text:

    pip install pillow
    python tools/make_graphics.py
"""

import math
import os
import random
import subprocess

from PIL import Image, ImageColor, ImageDraw, ImageFilter, ImageFont

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "images")

BANNER_TEXT = "Alex's Home Page"


def font_path(pattern):
    return subprocess.check_output(["fc-match", "-f", "%{file}", pattern], text=True)


SANS_BOLD = font_path("Liberation Sans:bold")
MONO_BOLD = font_path("Liberation Mono:bold")


def font(path, size):
    return ImageFont.truetype(path, size)


def draw_for(img):
    d = ImageDraw.Draw(img)
    d.fontmode = "1"  # no anti-aliasing: crisp 1998 pixels
    return d


def save(img, name):
    img.save(os.path.join(OUT, name))


def save_anim(frames, name, duration):
    frames[0].save(os.path.join(OUT, name), save_all=True, append_images=frames[1:],
                   duration=duration, loop=0, disposal=2)


def bevel(d, box, light, dark, face, width=2, outline="#000000"):
    x0, y0, x1, y1 = box
    d.rectangle(box, fill=face, outline=outline)
    for i in range(1, width + 1):
        d.line([(x0 + i, y1 - i), (x0 + i, y0 + i), (x1 - i, y0 + i)], fill=light)
        d.line([(x0 + i, y1 - i), (x1 - i, y1 - i), (x1 - i, y0 + i)], fill=dark)


def centered_text(d, box, text, fnt, fill, shadow=None, spacing=1):
    x0, y0, x1, y1 = box
    l, t, r, b = d.multiline_textbbox((0, 0), text, font=fnt, spacing=spacing, align="center")
    x = x0 + (x1 - x0 - (r - l)) // 2 - l
    y = y0 + (y1 - y0 - (b - t)) // 2 - t
    if shadow:
        d.multiline_text((x + 1, y + 1), text, font=fnt, fill=shadow, spacing=spacing, align="center")
    d.multiline_text((x, y), text, font=fnt, fill=fill, spacing=spacing, align="center")


# ---------------------------------------------------------------- background

def stars_tile():
    """Static starfield tile, plus the data the page needs to make it twinkle.

    script.js lays a grid over the page, one cell per repeat of this tile, and
    flares the bright stars listed in starfield.js on an independent random
    schedule in every cell, so no two tiles twinkle alike.
    """
    rnd = random.Random(1998)
    size = 320
    img = Image.new("RGB", (size, size), "#000000")
    px = img.load()
    dim = ["#333333", "#666666", "#999999", "#666699"]
    for _ in range(280):
        px[rnd.randrange(size), rnd.randrange(size)] = ImageColor.getrgb(rnd.choice(dim))
    d = draw_for(img)
    bright = []
    for _ in range(56):
        x, y = rnd.randrange(size), rnd.randrange(size)
        d.point((x, y), fill=rnd.choice(["#FFFFFF", "#CCCCCC", "#FFFFCC", "#99CCFF"]))
        bright.append((x, y))
    for _ in range(16):  # bright "plus" stars
        x, y = rnd.randrange(3, size - 3), rnd.randrange(3, size - 3)
        d.point([(x - 1, y), (x + 1, y), (x, y - 1), (x, y + 1)], fill="#999999")
        d.point((x, y), fill="#FFFFFF")
        bright.append((x, y))
    save(img, "stars.gif")

    points = ",".join(f"[{x},{y}]" for x, y in bright)
    with open(os.path.join(OUT, "..", "starfield.js"), "w") as f:
        f.write("// Generated by tools/make_graphics.py - bright stars in images/stars.gif\n")
        f.write(f"var STAR_TILE = {size};\n")
        f.write(f"var STAR_POINTS = [{points}];\n")


def twinkle_sprites():
    """Flare frames (small, big, biggest) in three star colours: twinkle_<c><n>.gif."""
    for key, colour in [("w", "#FFFFFF"), ("y", "#FFFFCC"), ("b", "#99CCFF")]:
        for n, arm in [(1, 1), (2, 3), (3, 4)]:
            img = Image.new("RGBA", (9, 9), (0, 0, 0, 0))
            sd = draw_for(img)
            c = 4
            sd.line([(c - arm, c), (c + arm, c)], fill="#666699")
            sd.line([(c, c - arm), (c, c + arm)], fill="#666699")
            sd.point([(c - 1, c), (c + 1, c), (c, c - 1), (c, c + 1)], fill=colour)
            if arm >= 3:
                sd.point([(c - 1, c - 1), (c + 1, c - 1), (c - 1, c + 1), (c + 1, c + 1)], fill="#333366")
            sd.point((c, c), fill="#FFFFFF")
            save(img, f"twinkle_{key}{n}.gif")


# ---------------------------------------------------------------- planets

def planet(name, ocean, land, spin, seed):
    size, r = 56, 22
    cx = cy = size // 2
    light = (-0.55, -0.5, 0.67)
    frames = []
    nframes = 20
    for f in range(nframes):
        img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
        px = img.load()
        phase = spin * 2 * math.pi * f / nframes
        for y in range(size):
            for x in range(size):
                nx, ny = (x - cx + 0.5) / r, (y - cy + 0.5) / r
                rr = nx * nx + ny * ny
                if rr > 1:
                    continue
                nz = math.sqrt(1 - rr)
                lon = math.atan2(nx, nz) + phase
                lat = math.asin(max(-1, min(1, ny)))
                v = (math.sin(3 * lon + seed) * math.cos(2 * lat)
                     + 0.6 * math.sin(5 * lon + 1.3 * seed) * math.sin(3 * lat + seed))
                shade = max(0.0, nx * light[0] + ny * light[1] + nz * light[2])
                level = min(3, int(shade * 4.2))  # banded shading, no smooth gradients
                pal = land if v > 0.35 else ocean
                if abs(lat) > 1.2:
                    pal = ["#666666", "#999999", "#CCCCCC", "#FFFFFF"]
                px[x, y] = ImageColor.getrgb(pal[level]) + (255,)
        frames.append(img)
    save_anim(frames, name, 90)


# ---------------------------------------------------------------- banner

def banner():
    w, h = 560, 84
    fnt = font(SANS_BOLD, 50)
    mask = Image.new("L", (w, h), 0)
    md = draw_for(mask)
    l, t, r, b = md.textbbox((0, 0), BANNER_TEXT, font=fnt)
    tx = (w - (r - l)) // 2 - l - 4
    ty = (h - (b - t)) // 2 - t - 4
    md.text((tx, ty), BANNER_TEXT, font=fnt, fill=255)
    outline = mask.filter(ImageFilter.MaxFilter(3))

    img = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    # 3-D extrusion down and to the right
    extrude = ["#330066", "#330066", "#330099", "#330099", "#6600CC", "#6600CC", "#9933FF"]
    for i, col in reversed(list(enumerate(extrude, start=1))):
        layer = Image.new("RGBA", (w, h), col)
        img.paste(layer, (i, i), outline)
    img.paste(Image.new("RGBA", (w, h), "#000000"), (0, 0), outline)
    # face filled with hard colour bands
    bands = Image.new("RGBA", (w, h))
    bd = ImageDraw.Draw(bands)
    stops = ["#FFFFCC", "#FFFF99", "#FFFF00", "#FFCC00", "#FF9900", "#FFCC00", "#FFFF00"]
    top, bottom = ty + t, ty + b
    step = (bottom - top) / len(stops)
    for i, col in enumerate(stops):
        bd.rectangle((0, int(top + i * step), w, int(top + (i + 1) * step) + 1), fill=col)
    bd.rectangle((0, 0, w, top), fill=stops[0])
    bd.rectangle((0, bottom, w, h), fill=stops[-1])
    img.paste(bands, (0, 0), mask)
    save(img, "banner.gif")


